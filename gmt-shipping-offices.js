  /* يحذف اسم الشركة من النص كي لا يُقرأ كاسم منطقة.
     السبب: «القدموس» و«بابل» أسماء **شركات ومدن معاً** — فجملة «ابعتها مع القدموس
     لدمشق» كانت تُقرأ وجهتُها «القدموس» (بلدة في طرطوس) بدل «دمشق». */
  function stripCompany(text, company) {
    var out = String(text || '');
    (COMPANY_ALIASES[company] || []).forEach(function (a) {
      var esc = a.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      out = out.replace(new RegExp('(^|\\s)(مع\\s+|عبر\\s+|شركة\\s+|شركه\\s+)?ال?' + esc + '(\\s|$)', 'g'), ' ');
    });
    return out.replace(/\s+/g, ' ').trim();
  }

  /* يرجع اسم الشركة إن ذُكرت في النص، وإلا '' */
  function companyInText(text) {
    var hay = ' ' + norm(text) + ' ';
    var best = '', bestLen = 0;
    Object.keys(COMPANY_ALIASES).forEach(function (co) {
      COMPANY_ALIASES[co].forEach(function (a) {
        var n = norm(a);
        if (n.length >= 4 && hay.indexOf(n) !== -1 && n.length > bestLen) { best = co; bestLen = n.length; }
      });
    });
    return best;
  }

  /* ══ حسم المكتب من نصّ العنوان — المنطق الكامل في مكان واحد ══
     يرجع كائن المكتب أو null. `formCompany` = ما اختاره الموظّف في النموذج (أقوى شيء). */
  function resolve(regionName, formCompany, rawText) {
    if (!regionName) return null;
    var inText = rawText ? companyInText(rawText) : '';
    var co = formCompany || inText || '';

    /* شركة محدَّدة (من النموذج أو من نصّ الرسالة) ⇒ نبحث داخلها وحدها */
    if (co && OFFICES[co]) {
      var r = pickWithin(regionName, co);
      if (r) { r.source = formCompany ? 'form' : 'text'; return r; }
      /* الشركة محدّدة لكن لا مكتب مطابق عندها ⇒ لا نقفز لشركة أخرى بصمت */
      return null;
    }

    /* بلا شركة ⇒ **المفتي أوّلاً دائماً** */
    var m = pickWithin(regionName, PRIMARY);
    if (m) { m.source = 'primary'; return m; }

    /* المفتي لا يملك هذا المكتب/المدينة ⇒ عندها فقط نأخذ من شركة أخرى */
    var others = Object.keys(OFFICES).filter(function (c) { return c !== PRIMARY; });
    for (var i = 0; i < others.length; i++) {
      var o = pickWithin(regionName, others[i]);
      if (o) { o.source = 'other'; return o; }
    }
    return null;
  }

  /* الحسم داخل شركة واحدة: مدينة ⇒ المكتب الافتراضي · وإلا اسم مكتب */
  function pickWithin(regionName, company) {
    if (!OFFICES[company]) return null;
    var m = mainOffice(regionName, company);          // مدينة؟ (يطابق مطبّعاً)
    if (m) return m;
    var list = all(company);
    for (var i = 0; i < list.length; i++) {
      if (sameName(list[i].name, regionName)) return list[i];
    }
    return null;
  }

