  function canonCompany(c) {
    var raw = String(c == null ? '' : c).trim();
    if (!raw) return '';
    /* نُزيل الكلمات الزائدة التي يكتبها الموظّف */
    var cleaned = raw.replace(/^(شركة|شركه|مكتب|مؤسسة|مؤسسه)\s+/, '')
                     .replace(/\s+(للشحن|للنقل|للشحن والنقل|اكسبرس|إكسبرس|express)$/i, '')
                     .trim();
    var keys = Object.keys(OFFICES).concat(Object.keys(TRACK_URLS)).concat(Object.keys(NO_TRACKING));
    var seen = {};
    for (var i = 0; i < keys.length; i++) {
      var k = keys[i];
      if (seen[k]) continue; seen[k] = 1;
      if (sameName(cleaned, k) || sameName(raw, k)) return k;
    }
    /* احتواءٌ جزئيّ: «المفتي للشحن السريع» ⇒ المفتي */
    var nc = norm(cleaned);
    for (var j = 0; j < keys.length; j++) {
      var kk = keys[j], nk = norm(kk), bk = bare(kk);
      if (!nk) continue;
      if (nc.indexOf(nk) !== -1 || nc.indexOf(bk) !== -1) return kk;
    }
    return raw;   /* شركةٌ لا نعرفها ⇒ تبقى كما كتبها (لا نخترع) */
  }

