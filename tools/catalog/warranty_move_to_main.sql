-- ① إزاحة الجدولين الفارغين القديمين (بنية مختلفة · 0 صفوف · لا يعتمد عليهما شيء)
do $$ begin
  if to_regclass('public.warranties_stub_unused') is null and exists (select 1 from information_schema.columns where table_schema='public' and table_name='warranties' and column_name='warranty_number') then
    alter table public.warranties rename to warranties_stub_unused; end if;
  if to_regclass('public.activation_logs_stub_unused') is null and exists (select 1 from information_schema.columns where table_schema='public' and table_name='activation_logs' and column_name='warranty_id') then
    alter table public.activation_logs rename to activation_logs_stub_unused; end if;
end $$;

