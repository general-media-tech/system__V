create or replace function public.gmt_warranties_touch() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;
drop trigger if exists trg_warranties_updated_at on public.warranties;
create trigger trg_warranties_updated_at before update on public.warranties for each row execute function public.gmt_warranties_touch();

