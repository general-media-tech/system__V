-- ③ الصلاحيات: نفس ما كان للصفحات (قراءة/إضافة/تعديل) — عدا سجلّ التفعيل: إضافة فقط
alter table public.warranties enable row level security;
alter table public.activation_logs enable row level security;
alter table public.contracts enable row level security;
alter table public.warranty_claims enable row level security;
do $$ declare t text; begin
  foreach t in array array['warranties','contracts','warranty_claims'] loop
    execute format('drop policy if exists gmt_read on public.%I', t);  execute format('create policy gmt_read on public.%I for select to anon, authenticated using (true)', t);
    execute format('drop policy if exists gmt_write on public.%I', t); execute format('create policy gmt_write on public.%I for insert to anon, authenticated with check (true)', t);
    execute format('drop policy if exists gmt_edit on public.%I', t);  execute format('create policy gmt_edit on public.%I for update to anon, authenticated using (true) with check (true)', t);
    execute format('grant select, insert, update on public.%I to anon, authenticated', t);
  end loop;
end $$;
drop policy if exists gmt_log_insert on public.activation_logs;
create policy gmt_log_insert on public.activation_logs for insert to anon, authenticated with check (true);
revoke all on public.activation_logs from anon, authenticated;
grant insert on public.activation_logs to anon, authenticated;

-- ④ التوقيع لصاحب الرابط فقط (رقم كفالة واحد ⇒ توقيعه) — بلا قراءة جماعية لسجلّ التفعيل
create or replace function public.gmt_warranty_signature(p_short_id text) returns text
language sql stable security definer set search_path = public as $$
  select l.signature_base64 from public.activation_logs l
  where l.short_id = p_short_id and l.signature_base64 is not null
  order by l.logged_at desc limit 1
$$;
revoke all on function public.gmt_warranty_signature(text) from public;
grant execute on function public.gmt_warranty_signature(text) to anon, authenticated;
