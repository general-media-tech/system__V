  function internalUI() {
    try { if (global.GMT_SURFACE) return global.GMT_SURFACE.internal(); } catch (e) {}
    if (global.GMT_PUBLIC === true || global.GMT_PUBLIC === 1) return false;
    return global.GMT_INTERNAL === true || global.GMT_INTERNAL === 1;
  }

  function page() {
    try { return decodeURIComponent((location.pathname.split('/').pop() || '')).toLowerCase(); }
    catch (e) { return ''; }
  }

  function seen() {
    try { return parseInt(localStorage.getItem(LS_KEY) || '0', 10) || 0; } catch (e) { return 0; }
  }
  function markSeen() {
    try { localStorage.setItem(LS_KEY, String(VERSION)); } catch (e) {}
  }

  /* بنود هذه الصفحة — البند بلا pages يظهر في كل صفحة داخلية */
  function forPage(p) {
    var me = p || page();
    return NEWS.filter(function (n) {
      if (!n.pages || !n.pages.length) return true;
      for (var i = 0; i < n.pages.length; i++)
        if (String(n.pages[i]).toLowerCase() === me) return true;
      return false;
    });
  }

  function unseenCount() {
    var s = seen();
    return forPage().filter(function (n) { return n.v > s; }).length;
  }

  function esc(s) {
    return String(s === null || s === undefined ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  }
  /* **غامق** ⇒ <b> — نكتب النصوص بعلامة بسيطة لا بHTML */
  function fmt(s) { return esc(s).replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>'); }

